// Walk floors and walls for every kit piece type, from the kit's own geometry (assets/walk-gen.js), written to
// assets/kit-walk.json for village.html (addKitAutoWalk). Run again after changing a kit builder:
//   node tools/gen-kit-walk.mjs            (all types)      node tools/gen-kit-walk.mjs sam_house ...   (just those)
// Types with hand-made decks (SamuraiKit.decks: piers, boats, bridges, stairs, the walkable dojos), rooms, characters and
// floating pieces are left out. Each entry carries the type's triangle count and size (sig): the village recomputes a
// type whose geometry no longer matches.
import fs from 'fs';
const REPO = new URL('..', import.meta.url).pathname;
globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => new Proxy({}, { get: () => () => ({ addColorStop() {} }) }) }) };
globalThis.BABYLON = new Proxy({}, { get: () => function () { return new Proxy({}, { get: () => () => {} }); } });
(0, eval)(fs.readFileSync(REPO + 'assets/samurai-kit.js', 'utf8'));
(0, eval)(fs.readFileSync(REPO + 'assets/walk-gen.js', 'utf8'));
const K = window.SamuraiKit, WG = window.WalkGen, OUT = REPO + 'assets/kit-walk.json';
const only = process.argv.slice(2);
const old = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : { types: {} };
const types = only.length ? only.filter(t => !t.startsWith('room_')) : K.types.filter(t => K.walkEligible(t));
const t0 = Date.now(), out = only.length ? old : { note: old.note, types: {} };
out.note = 'Generated by tools/gen-kit-walk.mjs from assets/samurai-kit.js (walk floors: [x0, z0, x1, z1, y]; walls: [x0, z0, x1, z1]; piece frame, metres)';
let nd = 0, nb = 0;
for (const t of types) {
  const M = new K._Kit(); K._B[t](M);
  const tri = K.walkTriangles(M.parts), r = WG.fromTriangles(tri.tris, {});
  if (!r) { delete out.types[t]; continue; } // soft parts only (a bush of leaves): no table, it walks as ground
  out.types[t] = { sig: tri.sig, decks: r.decks, walls: r.blockers };
  nd += r.decks.length; nb += r.blockers.length;
}
// rooms: from the room's spawn, at the room engine's step (.45); walls not widened (the room adds the body's radius), each
// with the floor level it stands at; floors only where the room's own decks are not (they own stages, stairs, galleries)
// and no higher than 2.6 m
const deckAt = (d, x, z) => { if (d.circle) { const [cx, cz, r] = d.circle; return (x - cx) ** 2 + (z - cz) ** 2 <= r * r; } const [x0, z0, x1, z1] = d.box; return x >= x0 && x <= x1 && z >= z0 && z <= z1; };
if (!only.length || only.some(t => t.startsWith('room_'))) {
  out.rooms = only.length ? (old.rooms || {}) : {};
  for (const [t, spec] of Object.entries(K.rooms)) {
    if (only.length && !only.includes(t)) continue;
    const parts = K.walkRoomParts(t), tri = K.walkTriangles(parts), decksOwn = spec.decks || [];
    // the signature is of the room's own builder (what the village can read back from its built template), not its parts
    const sig = K.walkTriangles(Object.fromEntries(Object.entries(parts).filter(([k]) => !k.includes('#')))).sig;
    const r = WG.fromTriangles(tri.tris, { seeds: [[spec.spawn[0], spec.spawn[1], spec.spawn[3] || 0]], stepUp: .45, inflate: 0, minFloor: .12, maxFloor: 2.6, skipFloor: (x, z) => decksOwn.some(d => deckAt(d, x, z)) });
    if (!r) { delete out.rooms[t]; continue; }
    // a room that lists its walk zones (tunnels, ledges) keeps the generated walls too (boulders, sacks, stairs inside the
    // zones), except any within 1.4 m of its spawn or exit: the zones already hold the body there
    const near = ([x0, z0, x1, z1], [px, pz]) => Math.hypot(Math.max(x0 - px, 0, px - x1), Math.max(z0 - pz, 0, pz - z1)) < 1.4;
    out.rooms[t] = { sig, decks: r.decks, walls: spec.walk ? r.blockers.filter(b => !near(b, spec.spawn) && !near(b, spec.exit)) : r.blockers };
    nd += r.decks.length; nb += r.blockers.length;
  }
  out.rooms = Object.fromEntries(Object.entries(out.rooms).sort(([a], [b]) => a < b ? -1 : 1));
}
out.types = Object.fromEntries(Object.entries(out.types).sort(([a], [b]) => a < b ? -1 : 1));
fs.writeFileSync(OUT, JSON.stringify(out).replace(/\],"/g, '],\n"').replace(/\{"sig"/g, '{\n "sig"') + '\n');
console.log(types.length, 'types,', nd, 'floors,', nb, 'walls,', ((Date.now() - t0) / 1000).toFixed(1), 's ->', OUT, (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB');
